#!/usr/bin/env node
// Generates src/environments/build-info.ts, which is gitignored. Run before
// every build/serve/test (see the npm script hooks in package.json) so the
// file always exists and is fresh.
//
// `secrets` picks up any FLUX_* environment variable present at build time.
// Anything shipped in a mobile bundle can be extracted by a determined user,
// so this is only for client-side keys (e.g. a Sentry DSN) — never real
// server secrets.
import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import pkg from '../package.json' with { type: 'json' };

let commit = 'unknown';
try {
  commit = execSync('git rev-parse --short HEAD').toString().trim();
} catch {
  // Not a git checkout (e.g. a source archive) — keep 'unknown'.
}

const secrets = {};
for (const [key, value] of Object.entries(process.env)) {
  if (key.startsWith('FLUX_')) {
    secrets[key] = value;
  }
}

const outFile = fileURLToPath(
  new URL('../src/environments/build-info.ts', import.meta.url)
);
mkdirSync(fileURLToPath(new URL('../src/environments', import.meta.url)), {
  recursive: true,
});

writeFileSync(
  outFile,
  `// Generated by scripts/write-build-info.mjs — do not edit or commit.
export const buildInfo = {
  version: ${JSON.stringify(pkg.version)},
  commit: ${JSON.stringify(commit)},
  secrets: ${JSON.stringify(secrets, null, 2)} as Record<string, string>,
};
`
);
